/**
 * Architecture Service: API Developer Portal Automated SDK Generator
 * Subsystem: API Communication Protocols & Ingress Management [API-INT-65]
 */

export interface ApiEndpointSchema {
  name: string;
  method: 'GET' | 'POST' | 'PUT' | 'DELETE';
  path: string;
  requestType?: string;
  responseType: string;
}

export class ApiPortalSdkGeneratorService {
  public generateTypeScriptSdk(sdkName: string, endpoints: ApiEndpointSchema[]): string {
    const lines: string[] = [
      `/**`,
      ` * Auto-generated TypeScript Client SDK: ${sdkName}`,
      ` * Generated by CodePulse API Portal SDK Generator`,
      ` */`,
      ``,
      `export interface SdkConfig {`,
      `  baseUrl: string;`,
      `  apiKey?: string;`,
      `}`,
      ``,
      `export class ${sdkName}Client {`,
      `  private baseUrl: string;`,
      `  private apiKey?: string;`,
      ``,
      `  constructor(config: SdkConfig) {`,
      `    this.baseUrl = config.baseUrl.replace(/\\/+$/, '');`,
      `    this.apiKey = config.apiKey;`,
      `  }`,
      ``,
      `  private async request<T>(method: string, path: string, body?: unknown): Promise<T> {`,
      `    const headers: Record<string, string> = { 'Content-Type': 'application/json' };`,
      `    if (this.apiKey) headers['Authorization'] = \`Bearer \${this.apiKey}\`;`,
      `    const res = await fetch(\`\${this.baseUrl}\${path}\`, {`,
      `      method,`,
      `      headers,`,
      `      body: body ? JSON.stringify(body) : undefined`,
      `    });`,
      `    if (!res.ok) throw new Error(\`API Error: \${res.status} \${res.statusText}\`);`,
      `    return res.json() as Promise<T>;`,
      `  }`
    ];

    for (const ep of endpoints) {
      const hasBody = ep.method === 'POST' || ep.method === 'PUT';
      const paramSig = hasBody && ep.requestType ? `payload: ${ep.requestType}` : '';
      const bodyArg = hasBody && ep.requestType ? 'payload' : 'undefined';

      lines.push(
        ``,
        `  public async ${ep.name}(${paramSig}): Promise<${ep.responseType}> {`,
        `    return this.request<${ep.responseType}>('${ep.method}', '${ep.path}', ${bodyArg});`,
        `  }`
      );
    }

    lines.push(`}`, ``);
    return lines.join('\n');
  }
}
