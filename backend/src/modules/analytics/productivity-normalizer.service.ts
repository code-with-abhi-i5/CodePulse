import { Injectable, Logger } from '@nestjs/common';
import { ChurnFilterService, FileDiffInput, ChurnAnalysisResult } from './churn-filter.service';

export interface DeveloperCommitContribution {
  commitSha: string;
  authorId: string;
  files: FileDiffInput[];
}

export interface NormalizedProductivityScore {
  authorId: string;
  rawLinesAdded: number;
  rawLinesDeleted: number;
  netMeaningfulLines: number;
  ignoredBloatLines: number;
  semanticPoints: number;
  normalizedContributionScore: number; // 0..100 fair rating
  antiGamingAssessment: {
    locGamingDetected: boolean;
    churnPenaltyPct: number;
    genuineContributionRatio: number;
  };
}

@Injectable()
export class ProductivityNormalizerService {
  private readonly logger = new Logger(ProductivityNormalizerService.name);

  constructor(private readonly churnFilter: ChurnFilterService) {}

  /**
   * Normalizes commit diffs into a fair productivity metric, eliminating LoC inflation.
   */
  public evaluateContribution(contribution: DeveloperCommitContribution): NormalizedProductivityScore {
    let rawAdded = 0;
    let rawDeleted = 0;
    let meaningfulAdded = 0;
    let meaningfulDeleted = 0;
    let ignoredBloat = 0;
    let totalSemanticPoints = 0;

    for (const file of contribution.files) {
      rawAdded += file.linesAdded;
      rawDeleted += file.linesDeleted;

      const analysis = this.churnFilter.filterFileDiff(file);

      if (analysis.isAutoGeneratedOrVendor) {
        ignoredBloat += file.linesAdded + file.linesDeleted;
        continue;
      }

      meaningfulAdded += analysis.meaningfulAdded;
      meaningfulDeleted += analysis.meaningfulDeleted;

      // Semantic AST-weighted scoring:
      // Test code = 2.0x weight, Logic/Algorithms = 2.5x weight, Documentation/Config = 0.5x weight
      const fileWeight = this.computeFileTypeWeight(file.filePath);
      const points = analysis.meaningfulAdded * fileWeight;
      totalSemanticPoints += points;
    }

    const netMeaningful = meaningfulAdded;
    const totalRaw = rawAdded + rawDeleted;

    // Detect LoC gaming: high raw lines (e.g. >2,000) with >80% ignored bloat
    const locGamingDetected = totalRaw > 1000 && (ignoredBloat / totalRaw) > 0.75;

    // Churn penalty: excessive deletion ratio without semantic additions
    let churnPenaltyPct = 0;
    if (meaningfulAdded + meaningfulDeleted > 100 && meaningfulDeleted > meaningfulAdded * 3) {
      churnPenaltyPct = 25; // 25% penalty for high thrash
    }

    // Normalized Score: logarithmic compression
    // Prevents 10,000 line bulk changes from skewing leaderboards
    const baseScore = totalSemanticPoints > 0 ? Math.log2(1 + totalSemanticPoints) * 10 : 0;
    const penalizedScore = baseScore * (1 - churnPenaltyPct / 100);
    const normalizedContributionScore = Math.min(100, Math.round(penalizedScore * 10) / 10);

    const genuineRatio = totalRaw > 0 ? Number(((meaningfulAdded + meaningfulDeleted) / totalRaw).toFixed(2)) : 1.0;

    return {
      authorId: contribution.authorId,
      rawLinesAdded: rawAdded,
      rawLinesDeleted: rawDeleted,
      netMeaningfulLines: netMeaningful,
      ignoredBloatLines: ignoredBloat,
      semanticPoints: Math.round(totalSemanticPoints),
      normalizedContributionScore,
      antiGamingAssessment: {
        locGamingDetected,
        churnPenaltyPct,
        genuineContributionRatio: genuineRatio,
      },
    };
  }

  private computeFileTypeWeight(filePath: string): number {
    const lower = filePath.toLowerCase();
    if (lower.includes('.spec.') || lower.includes('.test.')) {
      return 2.0; // High reward for test coverage
    }
    if (lower.endsWith('.ts') || lower.endsWith('.rs') || lower.endsWith('.go') || lower.endsWith('.py')) {
      return 2.5; // Core logic implementation
    }
    if (lower.endsWith('.md') || lower.endsWith('.txt')) {
      return 0.5; // Documentation
    }
    return 1.0;
  }
}
