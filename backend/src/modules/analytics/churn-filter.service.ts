import { Injectable, Logger } from '@nestjs/common';

export interface FileDiffInput {
  filePath: string;
  linesAdded: number;
  linesDeleted: number;
  patchContent?: string;
  isBinary?: boolean;
}

export interface ChurnAnalysisResult {
  filePath: string;
  isAutoGeneratedOrVendor: boolean;
  ignoredReason?: string;
  rawAdded: number;
  rawDeleted: number;
  meaningfulAdded: number;
  meaningfulDeleted: number;
  churnRatioPct: number;
}

@Injectable()
export class ChurnFilterService {
  private readonly logger = new Logger(ChurnFilterService.name);

  // Blacklist patterns for generated code, vendor bundles, and lockfiles
  private readonly ignoredPathPatterns: RegExp[] = [
    /(?:^|\/)(?:package-lock\.json|yarn\.lock|pnpm-lock\.yaml|Cargo\.lock|composer\.lock|poetry\.lock|Gemfile\.lock)$/i,
    /(?:^|\/)(?:\.next|\.nuxt|\.svelte-kit|dist|build|out|target|\.cache|coverage|node_modules)\//i,
    /\.(?:min\.js|min\.css|bundle\.js|bundle\.css|map|svg|png|jpg|jpeg|gif|ico|webp)$/i,
    /(?:\.d\.ts|\.generated\.ts|\.g\.dart|schema\.prisma\.gen)$/i,
    /(?:swagger|openapi)\.(?:json|yaml)$/i,
  ];

  /**
   * Evaluates whether a file is auto-generated, a vendor asset, or a lockfile.
   */
  public isIgnoredAsset(filePath: string): { isIgnored: boolean; reason?: string } {
    const normalized = filePath.replace(/\\/g, '/');

    for (const pattern of this.ignoredPathPatterns) {
      if (pattern.test(normalized)) {
        return { isIgnored: true, reason: `Matches noisy/generated asset pattern: ${pattern}` };
      }
    }

    return { isIgnored: false };
  }

  /**
   * Filters a batch of file diffs, removing non-semantic LoC bloat.
   */
  public filterFileDiff(file: FileDiffInput): ChurnAnalysisResult {
    const check = this.isIgnoredAsset(file.filePath);
    const totalRaw = file.linesAdded + file.linesDeleted;
    const churnRatioPct = totalRaw > 0 ? Number(((file.linesDeleted / totalRaw) * 100).toFixed(1)) : 0;

    if (check.isIgnored || file.isBinary) {
      return {
        filePath: file.filePath,
        isAutoGeneratedOrVendor: true,
        ignoredReason: check.reason || 'Binary asset',
        rawAdded: file.linesAdded,
        rawDeleted: file.linesDeleted,
        meaningfulAdded: 0,
        meaningfulDeleted: 0,
        churnRatioPct,
      };
    }

    // Inspect patch content to detect pure formatting churn (spaces, indentation)
    let meaningfulAdded = file.linesAdded;
    let meaningfulDeleted = file.linesDeleted;

    if (file.patchContent) {
      const lines = file.patchContent.split('\n');
      let nonWhitespaceAdded = 0;
      let nonWhitespaceDeleted = 0;

      for (const line of lines) {
        if (line.startsWith('+') && !line.startsWith('+++')) {
          if (line.substring(1).trim().length > 0) nonWhitespaceAdded++;
        } else if (line.startsWith('-') && !line.startsWith('---')) {
          if (line.substring(1).trim().length > 0) nonWhitespaceDeleted++;
        }
      }

      meaningfulAdded = nonWhitespaceAdded;
      meaningfulDeleted = nonWhitespaceDeleted;
    }

    return {
      filePath: file.filePath,
      isAutoGeneratedOrVendor: false,
      rawAdded: file.linesAdded,
      rawDeleted: file.linesDeleted,
      meaningfulAdded,
      meaningfulDeleted,
      churnRatioPct,
    };
  }
}
