import test from 'node:test';
import assert from 'node:assert/strict';

class HallucinationFilter {
  verifyExports(generatedCode, knownModuleExports) {
    const importRegex = /import\s*\{([^}]+)\}\s*from/g;
    const claimedExports = [];

    let match;
    while ((match = importRegex.exec(generatedCode)) !== null) {
      const items = match[1].split(',').map(s => s.trim()).filter(Boolean);
      claimedExports.push(...items);
    }

    const hallucinatedExports = claimedExports.filter(e => !knownModuleExports.includes(e));
    const validExports = claimedExports.filter(e => !hallucinatedExports.includes(e));
    const isHallucinated = hallucinatedExports.length > 0;

    const confidenceScore = claimedExports.length > 0
      ? Math.round((validExports.length / claimedExports.length) * 100) / 100
      : 1.0;

    return {
      isHallucinated,
      hallucinatedExports,
      validExports,
      confidenceScore
    };
  }
}

test('HallucinationFilter - flags non-existent module exports generated by LLM', () => {
  const filter = new HallucinationFilter();
  const known = ['Button', 'Card', 'Badge'];
  const code = 'import { Button, FakeWidget } from "./ui";';

  const res = filter.verifyExports(code, known);
  assert.strictEqual(res.isHallucinated, true);
  assert.strictEqual(res.hallucinatedExports[0], 'FakeWidget');
  assert.strictEqual(res.validExports[0], 'Button');
});
