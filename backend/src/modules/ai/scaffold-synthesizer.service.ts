import { Injectable, Logger, BadRequestException } from '@nestjs/common';
import { MermaidDiagramParser, ErGraph } from './scaffold-synthesizer/diagram-parser';
import { NestJsCodeGenerator, GeneratedFile } from './scaffold-synthesizer/code-generator';
import { ArchivePackager } from './scaffold-synthesizer/archive-packager';
import { GitHubCommitter } from './scaffold-synthesizer/github-committer';
import {
  ScaffoldFromDiagramDto,
  ScaffoldFromDiagramResponseDto,
  EntitySummaryDto,
} from './dto/scaffold-synthesizer.dto';

@Injectable()
export class ScaffoldSynthesizerService {
  private readonly logger = new Logger(ScaffoldSynthesizerService.name);
  private readonly parser = new MermaidDiagramParser();
  private readonly generator = new NestJsCodeGenerator();
  private readonly packager = new ArchivePackager();
  private readonly gitHubCommitter = new GitHubCommitter();

  /**
   * Synthesizes complete NestJS modules, controllers, services, DTOs,
   * and Prisma schemas from Mermaid architecture diagrams.
   */
  async synthesizeFromDiagram(
    dto: ScaffoldFromDiagramDto,
  ): Promise<ScaffoldFromDiagramResponseDto> {
    const { diagram, moduleName = 'GeneratedApp', packageAsZip = true, gitHubCommit } = dto;

    if (!diagram || !diagram.trim()) {
      throw new BadRequestException('Mermaid diagram content cannot be empty');
    }

    this.logger.log(`Synthesizing architecture scaffold for module: ${moduleName}`);

    // 1. Parse Mermaid diagram into Entity-Relationship Graph
    const erGraph: ErGraph = this.parser.parse(diagram);

    if (erGraph.entities.size === 0) {
      throw new BadRequestException(
        'No valid entity or class definitions could be identified from the provided Mermaid diagram. Ensure classDiagram or flowchart format is valid.',
      );
    }

    // 2. Generate complete NestJS code hierarchy and Prisma definitions
    const generatedFiles: GeneratedFile[] = this.generator.generate(erGraph, moduleName);

    // 3. Prepare summary of detected entities
    const entities: EntitySummaryDto[] = Array.from(erGraph.entities.values()).map((e) => ({
      name: e.name,
      tableName: e.tableName,
      fieldsCount: e.fields.length,
      relationsCount: e.relations.length,
    }));

    // 4. Package as Zip archive if requested
    let zipArchiveBase64: string | undefined;
    let zipFilename: string | undefined;
    let zipSizeBytes: number | undefined;

    if (packageAsZip) {
      const readme = this.generateReadme(moduleName, erGraph, generatedFiles, diagram);
      const zipResult = await this.packager.packageZip(generatedFiles, readme);
      zipArchiveBase64 = zipResult.base64;
      zipSizeBytes = zipResult.size;
      zipFilename = `${moduleName.toLowerCase()}-scaffold-${Date.now()}.zip`;
    }

    // 5. Commit to GitHub branch if configured
    let gitHubBranchUrl: string | undefined;
    if (gitHubCommit && gitHubCommit.owner && gitHubCommit.repo && gitHubCommit.targetBranch) {
      try {
        const commitResult = await this.gitHubCommitter.commitToBranch(generatedFiles, {
          token: gitHubCommit.token,
          owner: gitHubCommit.owner,
          repo: gitHubCommit.repo,
          baseBranch: gitHubCommit.baseBranch || 'main',
          targetBranch: gitHubCommit.targetBranch,
          commitMessage: gitHubCommit.commitMessage,
        });
        gitHubBranchUrl = commitResult.branchUrl;
      } catch (err: any) {
        this.logger.error(`GitHub commit failed: ${err.message}`, err.stack);
        // Do not fail entire scaffold synthesis if git commit encounters auth/network issue
        gitHubBranchUrl = `Error: ${err.message}`;
      }
    }

    const summary = `Successfully synthesized ${generatedFiles.length} files across ${entities.length} entities (${entities
      .map((e) => e.name)
      .join(', ')}). Generated NestJS Modules, Controllers, Services, validated DTOs, and Prisma schema.`;

    this.logger.log(summary);

    return {
      success: true,
      diagramType: erGraph.diagramType,
      moduleName,
      entities,
      generatedFiles,
      zipArchiveBase64,
      zipFilename,
      zipSizeBytes,
      gitHubBranchUrl,
      summary,
    };
  }

  private generateReadme(
    moduleName: string,
    graph: ErGraph,
    files: GeneratedFile[],
    originalDiagram: string,
  ): string {
    return [
      `# ${moduleName} - Synthesized Architecture Scaffold`,
      '',
      'Generated by CodePulse Architecture Diagram-to-Code Scaffolding Synthesizer.',
      '',
      '## Architecture Overview',
      '',
      '### Original Mermaid Diagram',
      '```mermaid',
      originalDiagram.trim(),
      '```',
      '',
      '### Generated Entities',
      ...Array.from(graph.entities.values()).map(
        (e) =>
          `- **${e.name}** (table: \`${e.tableName}\`): ${e.fields.length} fields, ${e.relations.length} relations`,
      ),
      '',
      '### Generated Files',
      ...files.map((f) => `- \`${f.path}\` (${f.type})`),
      '',
      '## Setup & Integration Instructions',
      '',
      '1. Copy the generated `src/modules` files into your NestJS project.',
      '2. Append the generated `prisma/schema.prisma` models into your primary `schema.prisma`.',
      '3. Run Prisma migration: `npx prisma migrate dev --name init_${moduleName.toLowerCase()}`',
      '4. Import `${moduleName}Module` into your root `AppModule`.',
      '',
    ].join('\n');
  }
}
